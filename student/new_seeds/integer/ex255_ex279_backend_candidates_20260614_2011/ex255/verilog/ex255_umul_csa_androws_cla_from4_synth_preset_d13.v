module ex255_umul_csa_androws_cla_from4(in, out);
  input [7:0] in;
  output [7:0] out;
  wire [3:0] a = in[3:0];
  wire [3:0] b = in[7:4];
  wire [7:0] row0 = ({8{b[0]}} & {4'b0, a});
  wire [7:0] row1 = ({8{b[1]}} & ({4'b0, a} << 1));
  wire [7:0] row2 = ({8{b[2]}} & ({4'b0, a} << 2));
  wire [7:0] row3 = ({8{b[3]}} & ({4'b0, a} << 3));
  wire [7:0] s0_0 = row0 ^ row1 ^ row2;
  wire [7:0] c0_0 = ((row0 & row1) | (row0 & row2) | (row1 & row2)) << 1;
  wire [7:0] s1_0 = s0_0 ^ c0_0 ^ row3;
  wire [7:0] c1_0 = ((s0_0 & c0_0) | (s0_0 & row3) | (c0_0 & row3)) << 1;
  wire [4:0] hcla_lo = s1_0[3:0] + c1_0[3:0];
  wire [7:0] cla_sum;
  assign cla_sum[0] = hcla_lo[0];
  assign cla_sum[1] = hcla_lo[1];
  assign cla_sum[2] = hcla_lo[2];
  assign cla_sum[3] = hcla_lo[3];
  wire hcla_cin = hcla_lo[4];
  wire [7:0] hcla_p = s1_0 ^ c1_0;
  wire [7:0] hcla_g = s1_0 & c1_0;
  assign cla_sum[4] = hcla_p[4] ^ hcla_cin;
  assign cla_sum[5] = hcla_p[5] ^ (hcla_g[4] | (hcla_p[4] & hcla_cin));
  assign cla_sum[6] = hcla_p[6] ^ (hcla_g[5] | (hcla_p[5] & hcla_g[4]) | (hcla_p[4] & hcla_p[5] & hcla_cin));
  assign cla_sum[7] = hcla_p[7] ^ (hcla_g[6] | (hcla_p[6] & hcla_g[5]) | (hcla_p[5] & hcla_p[6] & hcla_g[4]) | (hcla_p[4] & hcla_p[5] & hcla_p[6] & hcla_cin));
  assign out = cla_sum;
endmodule
