  assign cla_sum[6] = cla_p[6] ^ (cla_g[5] | (cla_p[5] & cla_g[4]) | (cla_p[4] & cla_p[5] & cla_g[3]) | (cla_p[3] & cla_p[4] & cla_p[5] & cla_g[2]) | (cla_p[2] & cla_p[3] & cla_p[4] & cla_p[5] & cla_g[1]) | (cla_p[1] & cla_p[2] & cla_p[3] & cla_p[4] & cla_p[5] & cla_g[0]));
