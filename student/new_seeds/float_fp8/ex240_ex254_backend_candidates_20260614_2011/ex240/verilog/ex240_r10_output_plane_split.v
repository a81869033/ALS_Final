        default: norm_sig = 4'h0;
      endcase
    end
  endfunction

  function [6:0] norm8;
    input [7:0] sigval;
    input [3:0] base_eff;
    reg [3:0] off;
    reg signed [5:0] exp_calc;
    reg [3:0] sig_round;
    reg [8:0] sub_k;
    begin
      if (sigval == 8'd0) norm8 = 7'h00;
      else begin
        off = norm_off(sigval);
        exp_calc = $signed({{2{off[3]}}, off}) + $signed({2'b00, base_eff});
        sig_round = norm_sig(sigval);
        if (exp_calc <= 0) begin
          sub_k = {1'b0, sigval} << (base_eff - 4'd1);
          norm8 = (sub_k > 9'd7) ? 7'h07 : sub_k[6:0];
        end else if ((exp_calc > 6'sd15) || ((exp_calc == 6'sd15) && (sig_round >= 4'd15))) begin
          norm8 = 7'h7e;
        end else begin
          norm8 = {exp_calc[3:0], sig_round[2:0]};
        end
      end
    end
  endfunction

  function [6:0] same_grs;
    input [8:0] ext_sum;
    input [3:0] max_eff;
    reg [4:0] exp_out;
    reg [4:0] sig_round;
    reg round_up;
    begin
      if (ext_sum[8]) begin
        exp_out = {1'b0, max_eff} + 5'd1;
        round_up = (ext_sum[4:0] > 5'd16) || ((ext_sum[4:0] == 5'd16) && ext_sum[5]);
        sig_round = {1'b0, ext_sum[8:5]} + {4'd0, round_up};
      end else begin
        exp_out = {1'b0, max_eff};
        round_up = (ext_sum[3:0] > 4'd8) || ((ext_sum[3:0] == 4'd8) && ext_sum[4]);
        sig_round = {1'b0, ext_sum[7:4]} + {4'd0, round_up};
        if (sig_round >= 5'd16) begin
          exp_out = exp_out + 5'd1;
          sig_round = 5'd8;
        end
      end
      if ((exp_out > 5'd15) || ((exp_out == 5'd15) && (sig_round >= 5'd15)))
        same_grs = 7'h7e;
      else if ((exp_out == 5'd1) && (sig_round < 5'd8))
        same_grs = {2'b00, sig_round};
      else
        same_grs = {exp_out[3:0], sig_round[2:0]};
    end
  endfunction

  wire [3:0] a_eff = (am[6:3] == 4'd0) ? 4'd1 : am[6:3];
  wire [3:0] b_eff = (bm[6:3] == 4'd0) ? 4'd1 : bm[6:3];
  wire [3:0] a_sig = (am[6:3] == 4'd0) ? {1'b0, am[2:0]} : {1'b1, am[2:0]};
  wire [3:0] b_sig = (bm[6:3] == 4'd0) ? {1'b0, bm[2:0]} : {1'b1, bm[2:0]};
  wire [3:0] max_eff = a_ge_b ? a_eff : b_eff;
  wire [3:0] min_eff = a_ge_b ? b_eff : a_eff;
  wire [3:0] gap = max_eff - min_eff;
  wire [3:0] max_sig = a_ge_b ? a_sig : b_sig;
  wire [3:0] min_sig = a_ge_b ? b_sig : a_sig;
  reg [8:0] min_aligned;
  always @* begin
    case (gap[2:0])
      3'd0: min_aligned = {1'b0, min_sig, 4'b0000};
      3'd1: min_aligned = {2'b00, min_sig, 3'b000};
      3'd2: min_aligned = {3'b000, min_sig, 2'b00};
      3'd3: min_aligned = {4'b0000, min_sig, 1'b0};
      3'd4: min_aligned = {5'b00000, min_sig};
      default: min_aligned = 9'd0;
    endcase
  end
  wire [8:0] ext_sum = {1'b0, max_sig, 4'b0000} + min_aligned;
  wire [6:0] same_mag = (gap >= 4'd5) ? maxc : same_grs(ext_sum, max_eff);
  wire [7:0] diff_sig = ({4'd0, max_sig} << gap[2:0]) - {4'd0, min_sig};
  wire [6:0] diff_norm = norm8(diff_sig, min_eff);
  wire gap5_down = (gap == 4'd5) && (max_sig == 4'd8) && (min_sig >= 4'd9);
  wire [6:0] diff_gap5 = maxc - {6'd0, gap5_down};
  wire [6:0] diff_mag = (maxc == minc) ? 7'h00 : ((gap >= 4'd6) ? maxc : ((gap == 4'd5) ? diff_gap5 : diff_norm));
  wire neg_zero = (am == 7'h00) && (bm == 7'h00) && a[7] && b[7];
  wire diff_sign = (diff_mag == 7'h00) ? 1'b0 : (a_ge_b ? a[7] : b[7]);
  function select_sign;
    input same_i;
    input neg_zero_i;
    input sign_a_i;
    input diff_sign_i;
    input [6:0] same_mag_i;
    begin
      select_sign = same_i ? ((same_mag_i == 7'h00) ? neg_zero_i : sign_a_i) : diff_sign_i;
    end
  endfunction
  function [6:0] select_mag;
    input same_i;
    input [6:0] same_mag_i;
    input [6:0] diff_mag_i;
    begin
      select_mag = same_i ? same_mag_i : diff_mag_i;
    end
  endfunction
  wire sel_sign = select_sign(same_sign, neg_zero, a[7], diff_sign, same_mag);
  wire [6:0] sel_mag = select_mag(same_sign, same_mag, diff_mag);
  assign out[7] = nan ? 1'b0 : sel_sign;
  assign out[6:0] = nan ? 7'h7f : sel_mag;
endmodule

