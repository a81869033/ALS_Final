module ex249_r26r_hypot_onehot_delta(in, out);
  input [15:0] in;
  output [7:0] out;
  wire [6:0] a = in[14:8];
  wire [6:0] b = in[6:0];
  wire nan = (a == 7'h7f) || (b == 7'h7f);
  wire a_ge_b = (a >= b);
  wire [6:0] maxc = a_ge_b ? a : b;
  wire [6:0] minc = a_ge_b ? b : a;
  wire [4:0] max_exp = maxc[6:2];
  wire [4:0] min_exp = minc[6:2];
  wire [2:0] smax = (max_exp == 5'd0) ? {1'b0, maxc[1:0]} : {1'b1, maxc[1:0]};
  wire [2:0] smin = (min_exp == 5'd0) ? {1'b0, minc[1:0]} : {1'b1, minc[1:0]};
  wire low_pair = (max_exp <= 5'd1) && (min_exp <= 5'd1);
  wire gap0 = (max_exp == min_exp) || low_pair;
  wire gap1 = ((min_exp <= 5'd1) && (max_exp == 5'd2)) || ((min_exp >= 5'd2) && (max_exp == (min_exp + 5'd1)));
  wire sm2 = (smax == 3'd2);
  wire sm3 = (smax == 3'd3);
  wire sm4 = (smax == 3'd4);
  wire sm5 = (smax == 3'd5);
  wire sm6 = (smax == 3'd6);
  wire sm7 = (smax == 3'd7);
  wire sn_ge2 = smin >= 3'd2;
  wire sn_ge3 = smin >= 3'd3;
  wire sn_ge4 = smin >= 3'd4;
  wire sn_ge5 = smin >= 3'd5;
  wire sn_ge6 = smin >= 3'd6;
  wire d2_g0 = (sm4 & sn_ge4) | (sm5 & sn_ge5) | (sm6 & sn_ge5) | (sm7 & sn_ge6);
  wire d1_g0_base = ((sm2 | sm3) & sn_ge2) | ((sm4 | sm5 | sm6 | sm7) & sn_ge3);
  wire d1_g1 = ((sm4 | sm5) & sn_ge5) | ((sm6 | sm7) & sn_ge6);
  wire delta1 = (gap0 & d1_g0_base & !d2_g0) | (gap1 & d1_g1);
  wire delta2 = gap0 & d2_g0;
  wire [1:0] delta = {delta2, delta1};
  wire sat = (maxc == 7'h7e) || ((maxc == 7'h7d) && delta2);
  wire [6:0] mag = sat ? 7'h7e : (maxc + {5'd0, delta});
  assign out = nan ? 8'h7f : {1'b0, mag};
endmodule
